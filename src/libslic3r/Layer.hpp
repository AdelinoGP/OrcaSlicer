// [INTENT] Layer.hpp — defines the Layer, LayerRegion, and SupportLayer data structures.
//
// The Layer hierarchy is the central data model for the slicing pipeline:
//   PrintObject (3D model)
//     └── Layer[] — horizontal cross-sections at each Z height
//           └── LayerRegion[] — per-PrintRegion sub-areas within the layer
//                 ├── slices (SurfaceCollection) — typed 2D surfaces (top/bottom/internal)
//                 ├── fill_surfaces (SurfaceCollection) — surfaces scheduled for infill
//                 ├── perimeters (ExtrusionEntityCollection) — perimeter toolpaths
//                 └── fills (ExtrusionEntityCollection) — infill toolpaths
//
// Data flow through a layer:
//   1. TriangleMeshSlicer → Layer::m_regions[i].slices (raw untyped surfaces)
//   2. detect_surfaces_type() → types slices as stTop/stBottom/stInternal
//   3. make_perimeters() → fills perimeters + thin_fills, updates fill_surfaces
//   4. make_fills() → fills LayerRegion::fills with infill toolpaths
//   5. GCode::process_layer() → emits G-code from perimeters + fills
//
// [MEMORY] LayerRegion objects are heap-allocated by Layer::add_region() and owned by
//   m_regions (vector of raw pointers). Layer::~Layer() deletes them explicitly.
//   No smart pointers — this is a hot path; smart_ptr overhead was deemed unacceptable.
//   Layer objects themselves are owned by PrintObject::m_layers (raw pointer vector).
// [COUPLING] Layer is tightly coupled to PrintObject (via m_object pointer),
//   PrintRegion (via LayerRegion::m_region), Fill system, and GCode pipeline.

